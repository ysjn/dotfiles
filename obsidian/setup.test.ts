import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, readdir, symlink, mkdir, readlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

const root = await mkdtemp(join(tmpdir(), 'obsidian-setup-'));
const vault = join(root, 'My Brain');
const run = (path: string) => spawnSync(process.execPath, ['--experimental-strip-types', new URL('./setup.ts', import.meta.url).pathname, path], { encoding: 'utf8' });
assert.equal(run(vault).status, 0);
assert.ok((await readdir(vault)).includes('00_Inbox'));
assert.equal(JSON.parse(await readFile(join(vault, '.obsidian/app.json'), 'utf8')).newFileFolderPath, '00_Inbox');
await writeFile(join(vault, 'MEMORY.md'), 'user memory');
await writeFile(join(vault, '.obsidian/app.json'), '{"user":true}');
assert.equal(run(vault).status, 0);
assert.equal(await readFile(join(vault, 'MEMORY.md'), 'utf8'), 'user memory');
assert.equal(await readFile(join(vault, '.obsidian/app.json'), 'utf8'), '{"user":true}');
const linked = join(root, 'linked');
await symlink(vault, linked);
assert.notEqual(run(linked).status, 0);
const codex = join(root, 'codex');
await mkdir(codex);
await writeFile(join(codex, 'AGENTS.md'), '# Existing user rules\n');
const link = () => spawnSync(process.execPath, ['--experimental-strip-types', new URL('./link-codex.ts', import.meta.url).pathname, vault, codex], { encoding: 'utf8' });
assert.equal(link().status, 0);
assert.equal(await readlink(join(codex, 'AGENTS.md')), join(vault, 'AGENTS.md'));
const merged = await readFile(join(vault, 'AGENTS.md'), 'utf8');
assert.ok(merged.includes('# Existing user rules'));
assert.ok(merged.includes('共通指示と外部メモリ'));
assert.ok((await readdir(codex)).some(name => name.startsWith('AGENTS.md.backup-')));
assert.equal(link().status, 0);
assert.equal(await readFile(join(vault, 'AGENTS.md'), 'utf8'), merged);
await writeFile(join(codex, 'AGENTS.override.md'), 'override');
assert.notEqual(link().status, 0);
console.log(`Passed: initial setup, repeat setup preserves notes/settings, symlink rejection (${root})`);
